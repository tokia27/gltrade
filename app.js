function updateModalPrice(productId) {
    const prod = findProduct(productId);
    if (!prod) return;
    let price = Number(prod.price) || 0;
    ['brand', 'size'].forEach(kind => {
        const sel = document.getElementById(`modal-${kind}-${productId}`);
        if (sel && sel.options[sel.selectedIndex]) {
            const p = sel.options[sel.selectedIndex].getAttribute('data-price');
            if (p) price = parseFloat(p);
        }
    });
    const el = document.getElementById(`modal-price-${productId}`);
    if (el) {
        el.textContent = `${money(price)} ₾`;
        el.dataset.price = price;
    }
    const old = document.getElementById(`modal-old-${productId}`);
    if (old && isPromoProduct(prod)) old.textContent = `${money(Math.round(price / (1 - prod.promo / 100)))} ₾`;
}

