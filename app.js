function saveUser(user) {
    if (!user) return;
    currentUser = user;
    writeStore('logged_user', user);
    const users = getUsersFromStorage();
    const idx = users.findIndex(u => (user.googleId && u.googleId === user.googleId) || (user.email && u.email === user.email));
    if (idx > -1) users[idx] = user; else users.push(user);
    writeStore('registered_users', users);
}

function parseJwt(token) {
    try {
        const base64Url = token.split('.')[1];
        const base64 = base64Url.replace(/-/g, '+').replace(/_/g, '/');
        const jsonPayload = decodeURIComponent(atob(base64).split('').map(function (c) {
            return '%' + ('00' + c.charCodeAt(0).toString(16)).slice(-2);
        }).join(''));
        return JSON.parse(jsonPayload);
    } catch (e) {
        console.error('JWT დეკოდირების შეცდომა:', e);
        return null;
    }
}

function handleCredentialResponse(response) {
    const payload = parseJwt(response && response.credential);
    if (!payload) {
        toast(t('googleFail'), 'error');
        return;
    }

    const email = payload.email;
    const name = payload.name || email;
    const googleId = payload.sub;

    const users = getUsersFromStorage();
    const foundUser = users.find(u => u.email === email || u.googleId === googleId);

    if (foundUser) {
        // ძველი შენახული ისტორია არ დაიკარგოს
        if (currentUser && currentUser.email === foundUser.email && currentUser.orderHistory && currentUser.orderHistory.length > (foundUser.orderHistory || []).length) {
            foundUser.orderHistory = currentUser.orderHistory;
        }
        if (!foundUser.googleId) foundUser.googleId = googleId;
        saveUser(foundUser);
        afterLogin();
        toast(`${t('welcomeBack')}, ${foundUser.username}!`);
    } else {
        pendingGoogleUser = {
            username: name,
            email: email,
            googleId: googleId,
            phone: '',
            address: '',
            pass: '',
            orderHistory: []
        };
        openModal('complete-profile-modal');
    }
}

