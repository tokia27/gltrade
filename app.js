let ROUTES = null;
function buildRoutes() {
    if (ROUTES) return ROUTES;
    const byPath = {}, catPaths = {}, prodPaths = {};
    Object.keys(PAGE_PATHS).forEach(page => { byPath[PAGE_PATHS[page]] = { type: 'page', page }; });
    CATEGORIES.forEach(c => {
        if (c.id === 'all') { catPaths['all|all'] = PAGE_PATHS.catalog; return; }
        const cSlug = slugify(c.name.ka) || slugify(c.id);
        const cPath = `${PAGE_PATHS.catalog}${cSlug}/`;
        catPaths[`${c.id}|all`] = cPath;
        byPath[cPath] = { type: 'catalog', cat: c.id, sub: 'all' };
        const used = {};
        c.subs.forEach(s => {
            let sSlug = slugify(s[1]) || slugify(s[0]);
            if (used[sSlug]) sSlug += '-' + slugify(s[0]);
            used[sSlug] = true;
            const sPath = `${cPath}${sSlug}/`;
            catPaths[`${c.id}|${s[0]}`] = sPath;
            byPath[sPath] = { type: 'catalog', cat: c.id, sub: s[0] };
        });
    });
    // პროდუქტები: id-ის მიხედვით, რომ მისამართები არ შეიცვალოს
    const usedSlugs = {};
    (typeof products !== 'undefined' ? products : []).slice().sort((a, b) => a.id - b.id).forEach(p => {
        const title = p.title || p.name || {};
        let slug = slugify(typeof title === 'object' ? (title.ka || title.en || '') : title) || ('produqti-' + p.id);
        if (usedSlugs[slug]) slug += '-' + p.id;
        usedSlugs[slug] = true;
        const path = `${PRODUCT_BASE}${slug}/`;
        prodPaths[p.id] = path;
        byPath[path] = { type: 'product', id: p.id };
    });
    ROUTES = { byPath, catPaths, prodPaths };
    return ROUTES;
}
function catPath(catId, subId) {
    const r = buildRoutes();
    return r.catPaths[`${catId || 'all'}|${subId || 'all'}`] || r.catPaths[`${catId}|all`] || PAGE_PATHS.catalog;
}
function productPath(id) {
    return buildRoutes().prodPaths[id] || PAGE_PATHS.catalog;
}
function normalizePath(pathname) {
    let p = decodeURI(pathname || '/');
    p = p.replace(/\/index\.html$/, '/');
    if (!p.endsWith('/')) p += '/';
    return p.replace(/\/{2,}/g, '/');
}
function parseRoute(pathname) {
    return buildRoutes().byPath[normalizePath(pathname)] || null;
}

