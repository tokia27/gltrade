// ფარდობითი მისამართი (images/x.jpg) -> /images/x.jpg, რომ ქვე-გვერდებზეც გამოჩნდეს
function assetUrl(src) {
    if (typeof src !== 'string' || !src) return src;
    if (/^(https?:|data:|blob:|\/)/.test(src)) return src;
    return '/' + src.replace(/^\.?\//, '');
}
