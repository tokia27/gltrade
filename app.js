function go(event, path) {
    if (event && (event.ctrlKey || event.metaKey || event.shiftKey || event.altKey || event.button === 1)) return true;
    if (event) event.preventDefault();
    navigate(path);
    return false;
}
function linkSub(event, i, j) {
    if (event && (event.ctrlKey || event.metaKey || event.shiftKey || event.altKey || event.button === 1)) return true;
    if (event) event.preventDefault();
    selectSub(i, j);
    return false;
}
function navigate(path, opts) {
    opts = opts || {};
    const route = parseRoute(path);
    if (!route) { showNotFound(opts); return; }
    if (route.type === 'page') {
        if (route.page === 'auth-section' && currentUser) { showPage('home', { replace: opts.replace, instant: opts.instant }); openProfileModal(); return; }
        if (route.page === 'catalog') { openCatalog('all', 'all', opts); return; }
        showPage(route.page, opts);
    } else if (route.type === 'catalog') {
        openCatalog(route.cat, route.sub, opts);
    } else if (route.type === 'product') {
        openProductPage(route.id, opts);
    }
}
