function categoryCount(catId) {
    if (catId in categoryCountCache) return categoryCountCache[catId];
    const list = typeof products !== 'undefined' ? products : [];
    const n = catId === 'all' ? list.length : list.filter(p => productInCat(p, catId)).length;
    categoryCountCache[catId] = n;
    return n;
}

function productMatchesQuery(prod, q) {
    if (!q) return true;
    const names = [prod.title, prod.name, prod.productName].map(v => {
        if (v && typeof v === 'object') return Object.values(v).join(' ');
        return v || '';
    }).join(' ').toLowerCase();
    let desc = '';
    if (Array.isArray(prod.description)) desc = prod.description.join(' ');
    else if (prod.description && typeof prod.description === 'object') desc = Object.values(prod.description).join(' ');
    else if (prod.description) desc = String(prod.description);
    const barcode = prod.barcode ? String(prod.barcode).toLowerCase() : '';
    return names.includes(q) || desc.toLowerCase().includes(q) || barcode.includes(q);
}

function getCatalogList() {
    let list = (typeof products !== 'undefined' ? products : []).slice();
    const q = catalogState.query.trim().toLowerCase();
    if (q) {
        list = list.filter(p => productMatchesQuery(p, q));
    } else if (catalogState.cat !== 'all') {
        list = catalogState.sub !== 'all'
            ? list.filter(p => productInSub(p, catalogState.cat, catalogState.sub))
            : list.filter(p => productInCat(p, catalogState.cat));
    }
    const s = catalogState.sort;
    if (s === 'price-asc') list.sort((a, b) => (Number(a.price) || 0) - (Number(b.price) || 0));
    else if (s === 'price-desc') list.sort((a, b) => (Number(b.price) || 0) - (Number(a.price) || 0));
    else if (s === 'name') list.sort((a, b) => productName(a).localeCompare(productName(b), currentLang));
    // ქვეკატეგორიის საკუთარი თანმიმდევრობა (მაგ. იატაკის მოსავლელი აქსესუარები)
    if (s === 'default' && !q && catalogState.sub !== 'all') {
        const rank = SUB_ORDER[normalizeCategoryValue(catalogState.sub)];
        if (rank) list.sort((a, b) => rank(a) - rank(b));
    }
    // მარაგში არმყოფი პროდუქტები ბოლოში
    if (s === 'default') list.sort((a, b) => (a.inStock === false) - (b.inStock === false));
    return list;
}

