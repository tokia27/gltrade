function repeatOrder(orderId) {
    if (!currentUser || !currentUser.orderHistory) return;
    const past = currentUser.orderHistory.find(o => o.orderId === orderId);
    if (!past) {
        toast(t('orderNotFound'), 'error');
        return;
    }
    past.cart.forEach(item => {
        const prod = findProduct(item.id);
        if (prod) {
            addItemToCart(prod, item.quantity || 1, item.selectedSize, item.selectedColor, item.price);
        } else {
            cart.push({ ...item, displayName: item.name, images: [] });
        }
    });
    updateCart();
    toast(t('repeatDone'));
    showPage('cart');
}

