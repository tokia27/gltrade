// 200 ₾-იანი ლიმიტი ეხება მხოლოდ ქვეკატეგორიას „საბეჭდი ქაღალდი“ (print_paper)
const PRINT_PAPER_SUB = 'print_paper';
const PAPER_MIN = 200;
