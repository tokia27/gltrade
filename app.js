async function checkout() {
    if (isCheckoutProcessing) return;

    if (!currentUser) {
        toast(t('loginToOrder'), 'error');
        showPage('auth-section');
        return;
    }
    if (!cart || cart.length === 0) {
        toast(t('emptyCartMsg'), 'error');
        return;
    }
    const buyer = validateBuyer();
    if (!buyer) return;

    const { paper, other } = cartTotals();
    if (!minOrderOk(paper, other)) {
        if (paper > 0) alert(`${t('paperOnlyMin')}\n${t('yourPaperTotal')}: ${money(paper)} ₾`);
        else alert(`${t('minOrderAlert')}\n${t('yourTotal')}: ${money(other)} ₾`);
        return;
    }

    isCheckoutProcessing = true;
    setCheckoutBtn(true);

    const orderId = '#' + Math.floor(10000 + Math.random() * 90000);
    const totalSum = cart.reduce((sum, item) => sum + (Number(item.price) * Number(item.quantity || 1)), 0).toFixed(2);
    // userInfo და address იგივე ფორმატშია, რასაც სერვერი უკვე იღებს — ახალი ინფორმაციაც მათშივე ჩანს
    const typeLabel = buyer.buyerType === 'company' ? 'იურიდიული პირი' : 'ფიზიკური პირი';
    // < > & სიმბოლოები სერვერზე (HTML შეტყობინებებში) შეცდომას იწვევს — ვცვლით
    const clean = (v) => String(v == null ? '' : v).replace(/[<>]/g, '').replace(/&/g, 'და').trim();
    Object.keys(buyer).forEach(k => { buyer[k] = clean(buyer[k]); });
    const userInfo = clean(`${typeLabel}: ${buyerSummary(buyer)} | ანგარიში: ${currentUser.username || ''}${currentUser.email ? ', ' + currentUser.email : ''}`);
    const address = buyer.address;
    const lang = currentLang || 'ka';

    const orderData = {
        orderId,
        userInfo,
        address,
        cart: cart.map(item => {
            let itemName = item.displayName || item.title || item.name || 'უცნობი პროდუქტი';
            if (typeof itemName === 'object') itemName = itemName[lang] || itemName.ka || Object.values(itemName)[0];
            const rawImages = Array.isArray(item.images) ? item.images : (item.images ? [item.images] : []);
            const fullUrlImages = rawImages.map(img => {
                if (typeof img === 'string' && img.startsWith('http')) return img;
                return `https://gltrade.ge/${String(img).replace(/^\/+/, '')}`;
            });
            return {
                id: item.id,
                barcode: item.barcode || '',
                name: itemName,
                price: Number(item.price),
                quantity: item.quantity || 1,
                images: fullUrlImages,
                selectedSize: item.selectedSize || null,
                selectedColor: item.selectedColor || null
            };
        }),
        totalSum: Number(totalSum),
        buyerType: buyer.buyerType,
        buyer,
        date: (function () {
            const d = new Date();
            const pad = (n) => String(n).padStart(2, '0');
            return `${pad(d.getDate())}.${pad(d.getMonth() + 1)}.${d.getFullYear()} ${pad(d.getHours())}:${pad(d.getMinutes())}`;
        })(),
        email: currentUser.email || '',
        account: currentUser.username || ''
    };

    // პროფილში ტელეფონი/მისამართი თუ არ ეწერა — ვინახავთ პირველი შეკვეთიდან
    if (!currentUser.phone || !currentUser.address) {
        if (!currentUser.phone) currentUser.phone = buyer.phone;
        if (!currentUser.address) currentUser.address = buyer.address;
        saveUser(currentUser);
    }

    try {
        const token = currentUser.token || (function () { try { return localStorage.getItem('auth_token'); } catch (e) { return null; } })();
        const headers = { 'Content-Type': 'application/json' };
        if (token) headers['Authorization'] = `Bearer ${token}`;

        const response = await fetch('https://gltrade-backend.onrender.com/api/checkout', {
            method: 'POST',
            headers: headers,
            body: JSON.stringify(orderData)
        });

        if (response.ok) {
            if (!currentUser.orderHistory) currentUser.orderHistory = [];
            currentUser.orderHistory.unshift({ ...orderData });
            saveUser(currentUser);
            cart = [];
            updateCart();
            isCheckoutProcessing = false;
            setCheckoutBtn(false);
            alert(`${t('orderSuccess')} ${orderId}\n\n${t('orderSuccessNote')}`);
            showPage('history-section');
        } else {
            let detail = '';
            try { detail = (await response.text()).slice(0, 300); } catch (e) { /* ignore */ }
            console.error('Checkout failed:', response.status, detail);
            isCheckoutProcessing = false;
            setCheckoutBtn(false);
            alert(`${t('orderError')}\n\n(${getLangText('შეცდომის კოდი', 'Error code', 'Код ошибки')}: ${response.status}${detail ? ' — ' + detail.replace(/<[^>]*>/g, ' ').replace(/\s+/g, ' ').trim().slice(0, 160) : ''})`);
        }
    } catch (err) {
        console.error('Checkout error:', err);
        isCheckoutProcessing = false;
        setCheckoutBtn(false);
        alert(t('serverError'));
    }
}

